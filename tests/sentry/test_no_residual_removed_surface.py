"""Manifest-driven residual sentry for the removed STORM concept (CLI repo).

Scans every tracked (and not-yet-tracked, non-ignored) path and file content,
case-insensitively, for the `storm` token, then checks an exact manifest of
forbidden old symbols, schema strings, config keys, routes, permissions,
commands and environment-variable names, plus the removed canary-check surface
(which the case-insensitive scan cannot see because `canary` is not `storm`).
The live CLI help tree and every `explain` topic are scanned too, so generated
help text cannot reintroduce an old name that no tracked source file spells.

Only the exact paths in `EXCEPTIONS` may keep an old literal. Each records its
purpose and whether it can reach a published artifact. Docs, tests and
migrations are NOT blanket-exempt. The scanner is exercised against seeded
violations in every surface class so a passing run is never vacuous.
"""


@pytest.mark.parametrize("surface", sorted(SEEDS))
def test_sentry_catches_seeded_violation(tmp_path: pathlib.Path, surface: str) -> None:
    rel, body = SEEDS[surface]
    target = tmp_path / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(body)
    assert scan(tmp_path, [rel]) != []


def test_sentry_catches_seeded_violation_in_help_text() -> None:
    assert scan_text("help:decoy x", "usage: decoy scan SOURCE") != []
    assert scan_text("explain:x", "STORM scans a dataset") != []
    assert scan_text("help:decoy x", "decoy pre-scan SOURCE") == []


def test_current_vocabulary_is_not_flagged(tmp_path: pathlib.Path) -> None:
    rel = "docs/ok.md"
    (tmp_path / "docs").mkdir()
    (tmp_path / rel).write_text(
        "decoy pre-scan data.csv\ndecoy post-scan integrity m.csv --source s.csv\n"
        "decoy post-scan fidelity s.csv o.csv\npost_scan:\n  integrity: true\n"
        "schema post-scan-integrity/v2\n"
    )
    assert scan(tmp_path, [rel]) == []


def test_exceptions_are_exact_and_documented() -> None:
    for exc in EXCEPTIONS:
        assert exc.purpose.strip()
        assert "*" not in exc.glob, f"exception must be an exact path, got {exc.glob!r}"
        assert (ROOT / exc.glob).is_file(), f"stale exception: {exc.glob}"
    assert not _excepted("src/decoy/cli/pre_scan.py")
    assert not _excepted("tests/unit/test_api.py")
    assert not _excepted("docs/cli-reference.md")
    assert not _excepted("docs/plans/new-plan.md")

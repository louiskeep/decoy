def _excepted(rel: str) -> bool:
    return any(fnmatch.fnmatchcase(rel, e.glob) for e in EXCEPTIONS)


def scan_text(rel: str, text: str) -> list[str]:
    hits: list[str] = []
    if STORM.search(text):
        hits.append(f"{rel}: content")
    for token in FORBIDDEN_TOKENS:
        if token in text:
            hits.append(f"{rel}: forbidden token {token!r}")
    return hits


def scan(root: pathlib.Path, rel_paths: list[str]) -> list[str]:
    """Return `path: reason` for every non-excepted residual in `rel_paths`."""
    hits: list[str] = []
    for rel in rel_paths:
        if _excepted(rel):
            continue
        if STORM.search(rel):
            hits.append(f"{rel}: path")
        hits.extend(f"{rel}: forbidden path token {t!r}" for t in FORBIDDEN_TOKENS if t in rel)
        path = root / rel
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        hits.extend(scan_text(rel, text))
    return hits


def _tracked() -> list[str]:
    git = shutil.which("git") or "git"
    out = subprocess.run(
        [git, "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return [rel for rel in out.splitlines() if (ROOT / rel).exists()]


def test_scanner_sees_the_real_tree() -> None:
    tracked = _tracked()
    assert "src/decoy/__main__.py" in tracked
    assert "docs/cli-reference.md" in tracked
    assert "src/decoy/cli/pre_scan.py" in tracked


def test_no_residual_removed_surface_in_tracked_files() -> None:
    assert scan(ROOT, _tracked()) == []


def _help_texts() -> dict[str, str]:
    """Rendered `--help` for every command in the live tree, plus every explain topic."""
    import typer
    import typer.core
    import typer.main

    from decoy.__main__ import app
    from decoy.cli.explain import _TOPICS

    out: dict[str, str] = {}

    def walk(cmd: typer.core.TyperCommand, path: list[str], parent: typer.Context | None) -> None:
        ctx = typer.Context(cmd, info_name=path[-1], parent=parent)
        out["help:" + " ".join(path)] = cmd.get_help(ctx)
        if isinstance(cmd, typer.core.TyperGroup):
            for name in cmd.list_commands(ctx):
                sub = cmd.get_command(ctx, name)
                if sub is not None:
                    walk(sub, [*path, name], ctx)

    walk(typer.main.get_command(app), ["decoy"], None)
    for name, topic in _TOPICS.items():
        out[f"explain:{name}"] = " ".join([topic.name, topic.summary, topic.body, *topic.see_also])
    return out


def test_live_help_and_explain_topics_carry_no_removed_surface() -> None:
    texts = _help_texts()
    assert len(texts) > 30  # the walk really covered the tree
    assert "help:decoy pre-scan fields" in texts and "help:decoy post-scan integrity" in texts
    hits = [h for key, text in texts.items() for h in scan_text(key, text)]
    assert hits == []



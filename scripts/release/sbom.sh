#!/usr/bin/env bash
# Generate a CycloneDX SBOM (JSON) for the CLI bundle's pinned third-party runtime.
#
# Usage: scripts/release/sbom.sh [PINS] [OUT]
#        scripts/release/sbom.sh --validate FILE    (schema-check an SBOM with the same tool)
#   PINS  requirements-format pin list (default: requirements-certified.txt)
#   OUT   output file (default: sbom.cdx.json in the current directory)
#
# Input is requirements-certified.txt, the repo's only runtime-profile pin list: the
# exact third-party closure of the certified DP runtime that the bundle's wheels
# (decoy-engine, decoy-engine-native, decoy-cli) are installed alongside. It carries no
# hashes, so components have none. requirements-dev.lock is the dev profile and is refused.
# The decoy-engine SBOM is generated by the engine repo's own scripts/release/sbom.sh.
#
# Tool: the upstream CycloneDX Python tool ("requirements" input), run from a throwaway venv
# installed from sbom-tool-requirements.txt, the fully resolved and hashed environment
# (cyclonedx-bom plus every transitive dependency), under
# `uv pip install --require-hashes --no-deps`: nothing is resolved at run time and a changed
# or tampered release fails the install. Regenerate it with sbom-tool-lock.sh. Network: the
# first run downloads those wheels (and CPython TOOL_PYTHON if uv does not have it) from
# PyPI; later runs reuse uv's cache. pyproject.toml and the locks are never touched.
#   https://cyclonedx-bom-tool.readthedocs.io/
#
# Reproducibility: --output-reproducible drops serialNumber and timestamp; SOURCE_DATE_EPOCH
# is unset so the environment cannot re-add a timestamp. Same pin list + same hashed tool
# environment give the same bytes. Exit is non-zero, and OUT is not written, on any failure.
#
# Not signed, not published; release wiring lives in the release workflow.
set -euo pipefail

TOOL_PYTHON="3.12"   # must match sbom-tool-lock.sh
SPEC_VERSION="1.6"

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
tool_reqs="$here/sbom-tool-requirements.txt"
checks="$here/sbom_checks.py"

die() { echo "sbom.sh: $*" >&2; exit 1; }

# A bare relative name such as "-x" must be read as a file, never as an option.
dotslash() { case "$1" in /*|./*|../*) printf '%s' "$1" ;; *) printf './%s' "$1" ;; esac; }

command -v uv >/dev/null 2>&1 || die "uv is required on PATH"
[ -f "$tool_reqs" ] || die "tool requirements file not found: $(basename "$tool_reqs")"
[ -f "$checks" ] || die "input checker not found: $(basename "$checks")"

mode=generate
if [ "${1:-}" = "--validate" ]; then
  mode=validate
  target="$(dotslash "${2:-?}")"
  [ -f "$target" ] || die "file to validate not found: $(basename "$target")"
else
  pins="$(dotslash "${1:-$root/requirements-certified.txt}")"
  out="$(dotslash "${2:-sbom.cdx.json}")"
  [ -f "$pins" ] || die "pin list not found: $(basename "$pins")"
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Throwaway tool environment from the hashed file; --require-hashes makes a missing or
# mismatching hash a hard failure, --no-deps stops uv resolving anything on its own.
{ uv venv -q --python "$TOOL_PYTHON" "$tmp/tool" \
  && uv pip install -q --python "$tmp/tool/bin/python" --require-hashes --no-deps -r "$tool_reqs"; } \
  >/dev/null 2>"$tmp/tool.err" \
  || { cat "$tmp/tool.err" >&2; die "tool environment install failed (hashes are enforced)"; }
py="$tmp/tool/bin/python"

if [ "$mode" = validate ]; then
  "$py" -I -c '
import json
import sys
from cyclonedx.schema import SchemaVersion
from cyclonedx.validation.json import JsonStrictValidator
t = open(sys.argv[1]).read()
v = SchemaVersion.from_version(json.loads(t)["specVersion"])
e = JsonStrictValidator(v).validate_str(t)
print("INVALID", e) if e else print("VALID")
sys.exit(1 if e else 0)' "$target"
  exit $?
fi

# Fail closed on anything but well-formed "name==version [; marker]" pins, their hash
# lines, whole-line comments and blanks: index URLs, local paths, git or direct URLs,
# options and inline comments would put infrastructure text into the SBOM.
"$py" -I "$checks" "$pins" || exit 1

pyproject="$(cd "$(dirname "$pins")" && pwd)/pyproject.toml"
pyproject_args=()
[ -f "$pyproject" ] && pyproject_args=(--pyproject "$pyproject" --mc-type application)

env -u SOURCE_DATE_EPOCH "$tmp/tool/bin/cyclonedx-py" requirements "$pins" \
  "${pyproject_args[@]}" --sv "$SPEC_VERSION" --output-reproducible --validate -o "$tmp/sbom.json" \
  || die "cyclonedx-py failed"

mkdir -p -- "$(dirname "$out")"
mv -- "$tmp/sbom.json" "$out"
echo "wrote $(basename "$out")" >&2

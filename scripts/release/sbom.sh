#!/usr/bin/env bash
# Generate a CycloneDX SBOM (JSON) for the CLI bundle's pinned third-party runtime.
#
# Usage: scripts/release/sbom.sh [PINS [OUT]]
#        scripts/release/sbom.sh --validate FILE    (schema-check an SBOM with the same tool)
#   PINS  requirements-format pin list (default: requirements-certified.txt)
#   OUT   output file (default: sbom.cdx.json in the current directory)
#
# Input is requirements-certified.txt, the repo's only runtime-profile pin list: the exact
# third-party closure of the certified DP runtime that the bundle's wheels (decoy-engine,
# decoy-engine-native, decoy-cli) are installed alongside. It carries no hashes, so
# components have none. requirements-dev.lock is the dev profile and is refused by the
# header scripts/dev/lock.sh writes into it. The root component always comes from the repo
# root's pyproject.toml ([project] name and version are required). The decoy-engine SBOM is
# generated by the engine repo's own scripts/release/sbom.sh.
#
# Tool: the upstream CycloneDX Python tool ("requirements" input), run as
# `python -I -m cyclonedx_py` from a throwaway CPython TOOL_PYTHON venv installed from
# sbom-tool-requirements.txt, the fully resolved and hashed environment (cyclonedx-bom plus
# every transitive dependency), under `uv pip install --require-hashes --no-deps
# --only-binary :all:`: nothing is resolved or built at run time, and a changed or tampered
# release fails the install. Every uv call runs with --no-config and without UV_* settings
# other than cache and transport, and -I keeps PYTHONPATH and user site out of the tool.
# Regenerate the tool file with sbom-tool-lock.sh. Network: the first run downloads those
# wheels (and CPython TOOL_PYTHON if uv does not have it) from PyPI; later runs reuse uv's
# cache. pyproject.toml and the locks are never touched.
#   https://cyclonedx-bom-tool.readthedocs.io/
#
# Checks (sbom_checks.py): the tool file's grammar before the install; the pin list's
# grammar, a packaging.requirements re-parse, one pin per package and the dev-lock header
# before generation; and after it, that the components equal the pins exactly.
#
# Reproducibility: --output-reproducible drops serialNumber and timestamp; SOURCE_DATE_EPOCH
# is unset so the environment cannot re-add a timestamp. Same pin list + same hashed tool
# environment give the same bytes. Exit is non-zero, and OUT is not written, on any failure.
#
# Not signed, not published; release wiring lives in the release workflow.
set -euo pipefail
unset CDPATH

TOOL_PYTHON="3.12"   # must match sbom-tool-lock.sh
SPEC_VERSION="1.6"

# Ambient uv settings must not choose the index, the interpreter or the build mode.
for v in $(compgen -e); do
  case "$v" in
    UV_CACHE_DIR|UV_NATIVE_TLS|UV_HTTP_TIMEOUT) ;;
    UV_*) unset "$v" ;;
  esac
done

here="$(cd -P -- "$(dirname -- "$0")" >/dev/null && pwd)"
root="$(cd -P -- "$here/../.." >/dev/null && pwd)"
tool_reqs="$here/sbom-tool-requirements.txt"
checks="$here/sbom_checks.py"
pyproject="$root/pyproject.toml"

die() { echo "sbom.sh: $*" >&2; exit 1; }
usage() { echo "usage: sbom.sh [PINS [OUT]] | sbom.sh --validate FILE" >&2; exit 2; }

# A bare relative name such as "-x" must be read as a file, never as an option.
dotslash() { case "$1" in /*|./*|../*) printf '%s' "$1" ;; *) printf './%s' "$1" ;; esac; }

command -v uv >/dev/null 2>&1 || die "uv is required on PATH"
[ -f "$tool_reqs" ] || die "tool requirements file not found: $(basename "$tool_reqs")"
[ -f "$checks" ] || die "input checker not found: $(basename "$checks")"

mode=generate
if [ "${1:-}" = "--validate" ]; then
  [ $# -eq 2 ] || usage
  mode=validate
  target="$(dotslash "$2")"
  [ -f "$target" ] || die "file to validate not found: $(basename "$target")"
else
  [ $# -le 2 ] || usage
  pins="$(dotslash "${1:-$root/requirements-certified.txt}")"
  out="$(dotslash "${2:-sbom.cdx.json}")"
  [ -f "$pins" ] || die "pin list not found: $(basename "$pins")"
  [ -f "$pyproject" ] || die "project metadata missing: pyproject.toml not found at the repo root"
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

uv venv -q --no-config --python "$TOOL_PYTHON" "$tmp/tool" >/dev/null 2>"$tmp/tool.err" \
  || { cat "$tmp/tool.err" >&2; die "tool environment install failed (no CPython $TOOL_PYTHON)"; }
py="$tmp/tool/bin/python"
"$py" -I -c 'import platform, sys
sys.exit(platform.python_implementation() != "CPython" or "%d.%d" % sys.version_info[:2] != sys.argv[1])' \
  "$TOOL_PYTHON" || die "tool interpreter is not CPython $TOOL_PYTHON"

# The checker is stdlib-only in this mode, so the bare interpreter can vet the tool file
# before uv reads it: hashed pins and comments only, no options, URLs or paths.
"$py" -I "$checks" pins-with-comments "$tool_reqs" || exit 1
uv pip install -q --no-config --python "$py" --require-hashes --no-deps --only-binary :all: \
  -r "$tool_reqs" >/dev/null 2>"$tmp/tool.err" \
  || { cat "$tmp/tool.err" >&2; die "tool environment install failed (hashes are enforced)"; }

if [ "$mode" = validate ]; then
  "$py" -I -c '
import json
import sys
from cyclonedx.schema import SchemaVersion
from cyclonedx.validation.json import JsonStrictValidator
t = open(sys.argv[1]).read()
v = SchemaVersion.from_version(json.loads(t)["specVersion"])
e = JsonStrictValidator(v).validate_str(t)
print("INVALID", e) if e else print("VALID")
sys.exit(1 if e else 0)' "$target"
  exit $?
fi

"$py" -I "$checks" runtime "$pins" || exit 1
"$py" -I "$checks" project "$pyproject" || exit 1

env -u SOURCE_DATE_EPOCH "$py" -I -m cyclonedx_py requirements "$pins" \
  --pyproject "$pyproject" --mc-type application \
  --sv "$SPEC_VERSION" --output-reproducible --validate -o "$tmp/sbom.json" \
  || die "cyclonedx-py failed"

"$py" -I "$checks" complete "$pins" "$tmp/sbom.json" || exit 1

mkdir -p -- "$(dirname "$out")"
mv -- "$tmp/sbom.json" "$out"
echo "wrote $(basename "$out")" >&2
